#!/usr/bin/env bash
# Install the minimal agent profile into a separate agent directory.
#
#   ./minimal/install.sh          # writes ~/.pi/minimal
#   PI_MINIMAL_DIR=… ./minimal/install.sh
#
# Why a separate agent dir: pi reads settings, SYSTEM.md and the extension
# config files from PI_CODING_AGENT_DIR, so a profile is exactly one variable.
# The daily profile in ~/.pi/agent stays untouched; the wrapper at
# <target>/pi sets the variable back.
#
# What the profile is: read/bash/edit/write plus codemode, every other tool
# reachable only from codemode scripts (PI_TOOL_EXPOSURE=deferred), and no
# tool descriptions or skill list in the system prompt. See docs/minimal.md.
set -euo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"
TARGET="${PI_MINIMAL_DIR:-$HOME/.pi/minimal}"
MAIN="${PI_MAIN_AGENT_DIR:-$HOME/.pi/agent}"
PI_BIN="$(command -v pi || true)"

[ -n "$PI_BIN" ] || { echo "install: pi is not on PATH" >&2; exit 1; }
[ -d "$REPO/node_modules" ] || echo "install: warning: $REPO/node_modules is missing — run npm install there" >&2

mkdir -p "$TARGET"
chmod 700 "$TARGET"

# settings.json is generated: the repo path is absolute because the profile
# is not inside the checkout, and model defaults are carried over from the
# daily profile so the trial does not start on a random model.
python3 - "$REPO" "$TARGET" "$MAIN" <<'PY'
import json, os, sys

repo, target, main = sys.argv[1:4]
carried = {}
main_settings = os.path.join(main, "settings.json")
if os.path.exists(main_settings):
    with open(main_settings) as handle:
        current = json.load(handle)
    for key in ("defaultProvider", "defaultModel", "defaultThinkingLevel", "theme"):
        if key in current:
            carried[key] = current[key]

settings = {
    "$schema": "https://pi.dev/schemas/settings.schema.json",
    **carried,
    # The declared set: file and shell work happens directly, everything else
    # goes through codemode (which is why it is enabled here).
    "defaultTools": ["read", "bash", "edit", "write", "+codemode"],
    "packages": [
        {
            "source": repo,
            "extensions": [
                "+extensions/env/index.ts",
                "+extensions/calendar/index.ts",
                "+extensions/gmail/index.ts",
                "+extensions/web-search/index.ts",
            ],
        }
    ],
}
with open(os.path.join(target, "settings.json"), "w") as handle:
    json.dump(settings, handle, indent=2)
    handle.write("\n")
PY

sed "s|@SKILLS_DIR@|$REPO/skills|g" "$REPO/minimal/SYSTEM.md" > "$TARGET/SYSTEM.md"

# Service configs come from the daily profile; credentials stay in the one
# env.json, which the wrapper points PI_ENV_CONFIG at. Existing copies are
# kept: editing a config in the minimal profile is allowed.
for name in gmail.json calendar.json; do
  if [ -f "$MAIN/$name" ] && [ ! -e "$TARGET/$name" ]; then
    cp "$MAIN/$name" "$TARGET/$name"
    chmod 600 "$TARGET/$name"
  fi
done

# pi's own provider credentials are per agent dir. Link, do not copy: a token
# refreshed in one profile must not go stale in the other.
for name in auth.json models.json mcp-auth.json; do
  if [ -f "$MAIN/$name" ] && [ ! -e "$TARGET/$name" ]; then
    ln -s "$MAIN/$name" "$TARGET/$name"
  fi
done

cat > "$TARGET/pi" <<EOF
#!/bin/sh
# Launch pi with the minimal profile (generated by minimal/install.sh).
export PI_CODING_AGENT_DIR="$TARGET"
export PI_ENV_CONFIG="$MAIN/env.json"
export PI_TOOL_EXPOSURE=deferred
exec "$PI_BIN" "\$@"
EOF
chmod +x "$TARGET/pi"

echo "minimal profile: $TARGET"
echo "run: $TARGET/pi"
